#!/usr/bin/env python3
"""Generate untrusted BFS witnesses. Lean proves coverage, semantics and lengths."""
from collections import deque
from pathlib import Path
import argparse


def generate(n: int) -> str:
    identity = tuple(range(n))
    words = {identity: ''}
    queue = deque([identity])
    while queue:
        p = queue.popleft()
        for c, q in [('l', p[1:] + p[:1]), ('r', p[-1:] + p[:-1]),
                     ('x', (p[1], p[0]) + p[2:])]:
            if q not in words:
                words[q] = words[p] + c
                queue.append(q)
    def decoded_codes(k):
        if k == 0:
            return [()]
        smaller = decoded_codes(k - 1)
        return [(i,) + tuple(0 if v + 1 == i else v + 1 for v in p)
                for i in range(k) for p in smaller]
    ordered_words = [words[p] for p in decoded_codes(n)]
    rows = ',\n  '.join('[' + ', '.join('.' + c for c in w) + ']' for w in ordered_words)
    if n == 6:
        from itertools import product
        checks = '\n'
        for first,second in product(range(6),range(5)):
            checks += f'''private theorem checked_first_{first}_{second} : ∀ c : PermCode 4,
    eval (table (({first} : Fin 6),({second} : Fin 5),c)) = decode (n := 6) (({first} : Fin 6),({second} : Fin 5),c) ∧
      (table (({first} : Fin 6),({second} : Fin 5),c)).length ≤ Nat.choose 6 2 := by
  decide +kernel

'''
        checks += f'''theorem checked : ∀ c : PermCode {n},
    eval (table c) = decode c ∧ (table c).length ≤ Nat.choose {n} 2 := by
  rintro ⟨i,j,c⟩
  fin_cases i <;> fin_cases j
'''
        checks += ''.join(f'  · exact checked_first_{i}_{j} c\n' for i,j in product(range(6),range(5))) + '\n'
    else:
        checks = f'''theorem checked : ∀ c : PermCode {n},
    eval (table c) = decode c ∧ (table c).length ≤ Nat.choose {n} 2 := by
  decide +kernel

'''
    return f'''import LRX.PermutationCode

/-! Generated by scripts/generate_small_certificates.py.
The generator is untrusted: ordinary kernel reduction checks all witnesses.
No `native_decide` is used. -/
namespace LRX.Small{n}
set_option maxRecDepth 100000
set_option maxHeartbeats 0

def words : Array (List Letter) := #[
  {rows}]

def table (c : PermCode {n}) : List Letter := words[codeIndex c]!

{checks}theorem sharp_words : SharpWordBound {n} := words_of_code_certificate table checked

theorem sharp_ediam : (graph {n}).ediam ≤ (Nat.choose {n} 2 : ℕ∞) :=
  sharp_ediam_of_words sharp_words

#print axioms sharp_ediam
end LRX.Small{n}
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('sizes', nargs='+', type=int)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for n in args.sizes:
        if not 4 <= n <= 6:
            parser.error('supported witness sizes: 4..6')
        target = Path(f'LRX/Small{n}.lean')
        text = generate(n)
        if args.check:
            if target.read_text() != text:
                raise SystemExit(f'FAIL: {target} differs from regenerated certificate')
            print(f'PASS: {target}')
        else:
            target.write_text(text)
